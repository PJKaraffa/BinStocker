-- Bin Stock Tracker: per-copy prices and globally unique copy barcodes.
-- Safe to rerun. Existing inventory and individual prices are preserved.
ALTER TABLE public.bin_inventory
  ADD COLUMN IF NOT EXISTS asking_price numeric(10,2)
    CHECK (asking_price IS NULL OR asking_price >= 0),
  ADD COLUMN IF NOT EXISTS copy_prices numeric(10,2)[];

CREATE TABLE IF NOT EXISTS public.bin_inventory_copies (
  copy_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stock_id uuid NOT NULL REFERENCES public.bin_inventory(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  barcode text GENERATED ALWAYS AS ('BS' || lpad(copy_id::text, 10, '0')) STORED UNIQUE,
  asking_price numeric(10,2) CHECK (asking_price IS NULL OR asking_price >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.bin_inventory_copies TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.bin_inventory_copies_copy_id_seq TO authenticated;

ALTER TABLE public.bin_inventory_copies ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view own stock copies" ON public.bin_inventory_copies;
DROP POLICY IF EXISTS "Users can add own stock copies" ON public.bin_inventory_copies;
DROP POLICY IF EXISTS "Users can update own stock copies" ON public.bin_inventory_copies;
DROP POLICY IF EXISTS "Users can delete own stock copies" ON public.bin_inventory_copies;
CREATE POLICY "Users can view own stock copies" ON public.bin_inventory_copies
  FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "Users can add own stock copies" ON public.bin_inventory_copies
  FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can update own stock copies" ON public.bin_inventory_copies
  FOR UPDATE TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can delete own stock copies" ON public.bin_inventory_copies
  FOR DELETE TO authenticated USING (auth.uid() = user_id);

-- Give every existing physical copy its own permanent barcode.
INSERT INTO public.bin_inventory_copies (stock_id, user_id, asking_price)
SELECT b.id, b.user_id,
       CASE WHEN cardinality(b.copy_prices) >= n.copy_number
            THEN b.copy_prices[n.copy_number]
            ELSE b.asking_price END
FROM public.bin_inventory AS b
CROSS JOIN LATERAL generate_series(1, GREATEST(COALESCE(b.bin_quantity, 1), 1)) AS n(copy_number)
WHERE NOT EXISTS (
  SELECT 1 FROM public.bin_inventory_copies AS c WHERE c.stock_id = b.id
);

